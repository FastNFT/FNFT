/* All single-exponential ES schemes use h^(j+1)*q^(j), including
 * boundary samples and subsampling. The tables are independent of the
 * implementation helpers. */
static INT test_es_family_preprocessing(void)
{
    static const REAL weights[3][7][7] = {
        {{0, 1, 0}, {-0.5, 0, 0.5}, {1, -2, 1}},
        {{0, 0, 1, 0, 0},
         {1.0/12, -2.0/3, 0, 2.0/3, -1.0/12},
         {-1.0/12, 4.0/3, -5.0/2, 4.0/3, -1.0/12},
         {-0.5, 1, 0, -1, 0.5}, {1, -4, 6, -4, 1}},
        {{0, 0, 0, 1, 0, 0, 0},
         {-1.0/60, 3.0/20, -3.0/4, 0, 3.0/4, -3.0/20, 1.0/60},
         {1.0/90, -3.0/20, 3.0/2, -49.0/18, 3.0/2, -3.0/20, 1.0/90},
         {1.0/8, -1, 13.0/8, 0, -13.0/8, 1, -1.0/8},
         {-1.0/6, 2, -13.0/2, 28.0/3, -13.0/2, 2, -1.0/6},
         {-0.5, 2, -2.5, 0, 2.5, -2, 0.5},
         {1, -6, 15, -20, 15, -6, 1}}
    };
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6, nse_discretization_ES8
    };
    const REAL steps[2] = {0.07, 1e-100};
    COMPLEX samples[9], *qp = NULL, *rp = NULL;
    INT ret_code = SUCCESS;

    for (UINT n=0; n<9; n++)
        samples[n] = 0.17+0.023*n*n+(COMPLEX)I*(0.09-0.04*n);
    for (UINT method=0; method<3; method++) {
        const UINT stride = 2*method+3;
        for (UINT step=0; step<2; step++) {
            for (UINT skip=1; skip<=2; skip++) {
                const REAL h = steps[step]*skip;
                for (INT kappa=-1; kappa<=1; kappa+=2) {
                    UINT Dsub = skip == 1 ? 9 : 5;
                    UINT first_last[2];
                    ret_code = nse_discretization_preprocess_signal(9,samples,
                            steps[step],kappa,&Dsub,&qp,&rp,first_last,
                            schemes[method]);
                    CHECK_RETCODE(ret_code, leave_fun);
                    if (Dsub != (skip == 1 ? 9U : 5U)
                            || first_last[0] != 0 || first_last[1] != 8) {
                        ret_code = E_TEST_FAILED;
                        goto leave_fun;
                    }
                    for (UINT n=0; n<Dsub; n++) {
                        for (UINT j=0; j<stride; j++) {
                            COMPLEX expected = 0.0;
                            for (UINT k=0; k<stride; k++) {
                                const INT index = (INT)(n*skip)
                                        +((INT)k-(INT)(stride/2))*(INT)skip;
                                if (index >= 0 && index < 9)
                                    expected += weights[method][j][k]*samples[index];
                            }
                            expected *= h;
                            {
                                const COMPLEX expected_r = -kappa*CONJ(expected);
                                const REAL q_error = CABS(
                                        qp[n*stride+j]-expected);
                                const REAL r_error = CABS(
                                        rp[n*stride+j]-expected_r);
                                const REAL tolerance = 2e3*EPSILON*h;
                                if (!isfinite(CREAL(qp[n*stride+j]))
                                        || !isfinite(CIMAG(qp[n*stride+j]))
                                        || !isfinite(CREAL(rp[n*stride+j]))
                                        || !isfinite(CIMAG(rp[n*stride+j]))
                                        || !isfinite(CREAL(expected))
                                        || !isfinite(CIMAG(expected))
                                        || !isfinite(CREAL(expected_r))
                                        || !isfinite(CIMAG(expected_r))
                                        || !isfinite(q_error)
                                        || !isfinite(r_error)
                                        || !isfinite(tolerance)
                                        || !(q_error <= tolerance)
                                        || !(r_error <= tolerance)) {
                                    ret_code = E_TEST_FAILED;
                                    goto leave_fun;
                                }
                            }
                        }
                    }
                    free(qp);
                    free(rp);
                    qp = rp = NULL;
                }
            }
        }
    }
leave_fun:
    free(qp);
    free(rp);
    return ret_code;
}

/* Constant potentials have no time derivatives: every ES order must
 * reproduce exp(h*Q) and its lambda derivative, as computed by BO. */
static INT test_es_family_constant(void)
{
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6, nse_discretization_ES8
    };
    const REAL h = 0.13;
    const COMPLEX value = 0.32-0.09*(COMPLEX)I;
    const COMPLEX lambda[2] = {0.0, 0.41+0.17*(COMPLEX)I};
    INT ret_code;

    for (UINT method=0; method<3; method++) {
        const UINT stride = 2*method+3;
        for (INT kappa=-1; kappa<=1; kappa+=2) {
            COMPLEX q[7] = {0}, r[7] = {0}, es[16], bo[16];
            const COMPLEX r_value = -kappa*CONJ(value);
            q[0] = h*value;
            r[0] = h*r_value;
            for (UINT derivative=0; derivative<=1; derivative++) {
                const UINT len = derivative ? 16 : 8;
                ret_code = nse_scatter_matrix(stride,q,r,h,kappa,2,lambda,
                        es,NULL,schemes[method],derivative);
                CHECK_RETCODE(ret_code, leave_fun);
                ret_code = nse_scatter_matrix(1,&value,&r_value,h,kappa,2,
                        lambda,bo,NULL,nse_discretization_BO,derivative);
                CHECK_RETCODE(ret_code, leave_fun);
                for (UINT j=0; j<len; j++) {
                    if (!isfinite(CREAL(es[j])) || !isfinite(CIMAG(es[j]))
                            || !isfinite(CREAL(bo[j]))
                            || !isfinite(CIMAG(bo[j])))
                        return E_TEST_FAILED;
                    {
                        const REAL error = CABS(es[j]-bo[j]);
                        const REAL tolerance = 500*EPSILON*(1+CABS(bo[j]));
                        if (!isfinite(error) || !isfinite(tolerance)
                                || !(error <= tolerance))
                            return E_TEST_FAILED;
                    }
                }
            }
            ret_code = nse_scatter_matrix_pade(stride,q,r,h,kappa,2,lambda,
                    es,NULL,schemes[method],1,0);
            CHECK_RETCODE(ret_code, leave_fun);
            for (UINT i=0; i<2; i++) {
                const COMPLEX z0 = -(COMPLEX)I*h*lambda[i];
                const COMPLEX z1 = h*value;
                const COMPLEX z2 = h*r_value;
                const COMPLEX delta = z0*z0+z1*z2;
                const COMPLEX denominator = 1.0-delta/4.0;
                const COMPLEX expected[4] = {
                    (1.0+delta/4.0+z0)/denominator,
                    z1/denominator, z2/denominator,
                    (1.0+delta/4.0-z0)/denominator
                };
                REAL error;
                for (UINT j=0; j<4; j++) {
                    if (!isfinite(CREAL(es[4*i+j]))
                            || !isfinite(CIMAG(es[4*i+j]))
                            || !isfinite(CREAL(expected[j]))
                            || !isfinite(CIMAG(expected[j])))
                        return E_TEST_FAILED;
                }
                error = misc_rel_err(4,&es[4*i],expected);
                if (!isfinite(error) || !(error <= 500*EPSILON))
                    return E_TEST_FAILED;
            }
            {
                const REAL invariant_error = FABS(CABS(es[0])*CABS(es[0])
                        +kappa*CABS(es[1])*CABS(es[1])-1.0);
                if (!isfinite(CREAL(es[0])) || !isfinite(CIMAG(es[0]))
                        || !isfinite(CREAL(es[1]))
                        || !isfinite(CIMAG(es[1]))
                        || !isfinite(invariant_error)
                        || !(invariant_error <= 1e-12))
                    return E_TEST_FAILED;
            }
        }
    }
    return SUCCESS;
leave_fun:
    return ret_code;
}

static INT test_step(const INT kappa, const UINT pade_degree)
{
    const REAL h = 0.13, delta = 1e-6;
    const COMPLEX lambda = 0.31 + 0.17 * I;
    const COMPLEX real_lambda = 0.31;
    const COMPLEX samples[7] = {0.31 - 0.11 * I, 0.43 + 0.07 * I, 0.48 - 0.05 * I, 0.53 + 0.14 * I,
                                0.46 - 0.19 * I, 0.39 + 0.08 * I, 0.28 - 0.03 * I};
    COMPLEX rsamples[7], q[7], r[7], M[8], Mp[4], Mm[4], Mn[4];
    INT W = 0, ret_code;
    for (UINT i = 0; i < 7; i++)
        rsamples[i] = -kappa * CONJ(samples[i]);
    es8_pack(samples, h, q);
    es8_pack(rsamples, h, r);
    ret_code =
        test_scatter_matrix(7, q, r, h, kappa, 1, &lambda, M, NULL,
                nse_discretization_ES8, pade_degree, 1);
    CHECK_RETCODE(ret_code, leave_fun);
    {
        const COMPLEX lp = lambda + delta, lm = lambda - delta;
        ret_code =
            test_scatter_matrix(7, q, r, h, kappa, 1, &lp, Mp, NULL,
                    nse_discretization_ES8, pade_degree, 0);
        CHECK_RETCODE(ret_code, leave_fun);
        ret_code =
            test_scatter_matrix(7, q, r, h, kappa, 1, &lm, Mm, NULL,
                    nse_discretization_ES8, pade_degree, 0);
        CHECK_RETCODE(ret_code, leave_fun);
    }
    for (UINT i = 0; i < 4; i++)
        Mp[i] = (Mp[i] - Mm[i]) / (2.0 * delta);
    {
        REAL error;
        for (UINT i=0; i<4; i++) {
            if (!isfinite(CREAL(M[4+i])) || !isfinite(CIMAG(M[4+i]))
                    || !isfinite(CREAL(Mp[i])) || !isfinite(CIMAG(Mp[i])))
                return E_TEST_FAILED;
        }
        error = misc_rel_err(4,&M[4],Mp);
        if (!isfinite(error) || !(error <= 2e-9))
            return E_TEST_FAILED;
    }
    ret_code =
        test_scatter_matrix(7, q, r, h, kappa, 1, &real_lambda, Mn, NULL,
                nse_discretization_ES8, pade_degree, 0);
    CHECK_RETCODE(ret_code, leave_fun);
    {
        const REAL invariant_error = FABS(CABS(Mn[0])*CABS(Mn[0])
                +kappa*CABS(Mn[1])*CABS(Mn[1])-1.0);
        if (!isfinite(CREAL(Mn[0])) || !isfinite(CIMAG(Mn[0]))
                || !isfinite(CREAL(Mn[1])) || !isfinite(CIMAG(Mn[1]))
                || !isfinite(invariant_error)
                || !(invariant_error <= 1e-12))
            return E_TEST_FAILED;
    }
    ret_code = test_scatter_matrix(7, q, r, h, kappa, 1, &lambda, Mn, &W,
            nse_discretization_ES8, pade_degree, 0);
    CHECK_RETCODE(ret_code, leave_fun);
    for (UINT i = 0; i < 4; i++)
        Mn[i] *= POW(2, W);
    {
        REAL error;
        for (UINT i=0; i<4; i++) {
            if (!isfinite(CREAL(M[i])) || !isfinite(CIMAG(M[i]))
                    || !isfinite(CREAL(Mn[i])) || !isfinite(CIMAG(Mn[i])))
                return E_TEST_FAILED;
        }
        error = misc_rel_err(4,M,Mn);
        if (!isfinite(error) || !(error <= 100*EPSILON))
            return E_TEST_FAILED;
    }
leave_fun:
    return ret_code;
}

static INT test_all_slow_pade_paths(void)
{
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6,
        nse_discretization_ES8
    };
    const REAL h = 0.06, delta = 1e-6;
    const REAL T[2] = {-0.24, 0.24};
    const COMPLEX lambda[2] = {
        0.27+0.19*(COMPLEX)I, -0.16+0.31*(COMPLEX)I
    };
    const COMPLEX continuous_lambda[2] = {-0.67,0.91};
    COMPLEX samples[9];
    COMPLEX *q = NULL, *r = NULL;
    INT ret_code = SUCCESS;

    for (UINT n=0; n<9; n++)
        samples[n] = 0.23+0.017*n*n+(COMPLEX)I*(0.11-0.026*n);
    for (UINT method=0; method<3; method++) {
        const UINT stride = 2*method+3;
        for (INT kappa=-1; kappa<=1; kappa+=2) {
            UINT Dsub = 9, first_last[2];
            ret_code = nse_discretization_preprocess_signal(9,samples,h,
                    kappa,&Dsub,&q,&r,first_last,schemes[method]);
            CHECK_RETCODE(ret_code, leave_fun);
            if (Dsub != 9 || first_last[0] != 0 || first_last[1] != 8) {
                ret_code = E_TEST_FAILED;
                goto leave_fun;
            }
            for (UINT degree=0; degree<=7; degree++) {
                COMPLEX matrix[16], normalized[16], plus[4], minus[4];
                COMPLEX bound_state = 0.17+4.0*(COMPLEX)I;
                COMPLEX a[2], aprime[2], b[2];
                INT W[2] = {0}, Ws = 0;

                ret_code = test_scatter_matrix(Dsub*stride,q,r,h,kappa,2,
                        lambda,matrix,NULL,schemes[method],degree,1);
                CHECK_RETCODE(ret_code, leave_fun);
                ret_code = test_scatter_matrix(Dsub*stride,q,r,h,kappa,2,
                        lambda,normalized,W,schemes[method],degree,1);
                CHECK_RETCODE(ret_code, leave_fun);
                for (UINT i=0; i<2; i++) {
                    for (UINT j=0; j<8; j++) {
                        const COMPLEX scaled = normalized[8*i+j]*POW(2,W[i]);
                        const REAL error = CABS(matrix[8*i+j]-scaled);
                        const REAL tolerance = 500*EPSILON
                                *(1+CABS(matrix[8*i+j]));
                        if (!isfinite(CREAL(matrix[8*i+j]))
                                || !isfinite(CIMAG(matrix[8*i+j]))
                                || !isfinite(CREAL(scaled))
                                || !isfinite(CIMAG(scaled))
                                || !isfinite(error) || !isfinite(tolerance)
                                || !(error <= tolerance)) {
                            ret_code = E_TEST_FAILED;
                            goto leave_fun;
                        }
                    }
                    if (W[i] == 0 && memcmp(&matrix[8*i],&normalized[8*i],
                            8*sizeof(COMPLEX)) != 0) {
                        ret_code = E_TEST_FAILED;
                        goto leave_fun;
                    }
                }
                {
                    const COMPLEX lambda_plus = lambda[0]+delta;
                    const COMPLEX lambda_minus = lambda[0]-delta;
                    ret_code = test_scatter_matrix(Dsub*stride,q,r,h,kappa,
                            1,&lambda_plus,plus,NULL,schemes[method],degree,0);
                    CHECK_RETCODE(ret_code, leave_fun);
                    ret_code = test_scatter_matrix(Dsub*stride,q,r,h,kappa,
                            1,&lambda_minus,minus,NULL,schemes[method],degree,0);
                    CHECK_RETCODE(ret_code, leave_fun);
                    for (UINT j=0; j<4; j++) {
                        const COMPLEX finite_difference =
                                (plus[j]-minus[j])/(2.0*delta);
                        const REAL error = CABS(matrix[4+j]
                                -finite_difference);
                        const REAL tolerance = 2e-8
                                *(1+CABS(finite_difference));
                        if (!isfinite(CREAL(finite_difference))
                                || !isfinite(CIMAG(finite_difference))
                                || !isfinite(error) || !isfinite(tolerance)
                                || !(error <= tolerance)) {
                            ret_code = E_TEST_FAILED;
                            goto leave_fun;
                        }
                    }
                }
                ret_code = test_scatter_bound_states(Dsub*stride,q,r,T,
                        bound_state,&a[0],&aprime[0],&b[0],NULL,
                        schemes[method],degree);
                CHECK_RETCODE(ret_code, leave_fun);
                ret_code = test_scatter_bound_states(Dsub*stride,q,r,T,
                        bound_state,&a[1],&aprime[1],&b[1],&Ws,
                        schemes[method],degree);
                CHECK_RETCODE(ret_code, leave_fun);
                if (Ws == 0) {
                    ret_code = E_TEST_FAILED;
                    goto leave_fun;
                }
                {
                    const COMPLEX scaled_a = a[1]*POW(2,Ws);
                    const COMPLEX scaled_aprime = aprime[1]*POW(2,Ws);
                    const REAL errors[3] = {CABS(a[0]-scaled_a),
                        CABS(aprime[0]-scaled_aprime),CABS(b[0]-b[1])};
                    const REAL tolerances[3] = {
                        500*EPSILON*(1+CABS(a[0])),
                        500*EPSILON*(1+CABS(aprime[0])),
                        500*EPSILON*(1+CABS(b[0]))
                    };
                    for (UINT j=0; j<3; j++) {
                        if (!isfinite(errors[j]) || !isfinite(tolerances[j])
                                || !(errors[j] <= tolerances[j])) {
                            ret_code = E_TEST_FAILED;
                            goto leave_fun;
                        }
                    }
                }
                for (UINT normalization=0; normalization<=1;
                        normalization++) {
                    COMPLEX full[8], H11[2], H21[2];
                    INT Wfull[2] = {0}, Wcolumn[2] = {0};
                    akns_discretization_t akns_discretization;
                    INT * const Wfull_ptr = normalization ? Wfull : NULL;
                    INT * const Wcolumn_ptr = normalization ? Wcolumn : NULL;

                    ret_code = test_scatter_matrix(Dsub*stride,q,r,h,kappa,
                            2,continuous_lambda,full,Wfull_ptr,
                            schemes[method],degree,0);
                    CHECK_RETCODE(ret_code, leave_fun);
                    ret_code = nse_discretization_to_akns_discretization(
                            schemes[method],&akns_discretization);
                    CHECK_RETCODE(ret_code, leave_fun);
                    ret_code = akns_scatter_matrix_first_column(Dsub*stride,
                            q,r,h,2,continuous_lambda,H11,H21,Wcolumn_ptr,
                            akns_discretization,degree);
                    CHECK_RETCODE(ret_code, leave_fun);
                    for (UINT i=0; i<2; i++) {
                        if (memcmp(&H11[i],&full[4*i],sizeof(COMPLEX)) != 0
                                || memcmp(&H21[i],&full[4*i+2],
                                    sizeof(COMPLEX)) != 0
                                || (normalization
                                    && Wcolumn[i] != Wfull[i])) {
                            ret_code = E_TEST_FAILED;
                            goto leave_fun;
                        }
                    }
                }
            }
            free(q);
            free(r);
            q = r = NULL;
        }
    }

leave_fun:
    free(q);
    free(r);
    return ret_code;
}

/* Exercise normalization outside its no-op range. A zero potential and an
 * imaginary spectral point produce reciprocal growing and decaying diagonal
 * entries, so both high and low finite magnitudes are reconstructed. */
static INT test_slow_ES_normalization_rescaling(void)
{
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6,
        nse_discretization_ES8
    };
    enum { nodes = 32 };
    const REAL h = 0.05;
    const COMPLEX lambda = 10.0*(COMPLEX)I;
    COMPLEX q[7*nodes] = {0}, r[7*nodes] = {0};
    INT ret_code = SUCCESS;

    for (UINT method=0; method<3; method++) {
        const UINT stride = 2*method+3;
        const UINT D = nodes*stride;

        for (INT kappa=-1; kappa<=1; kappa+=2) {
            for (UINT degree=0; degree<=7; degree++) {
                COMPLEX unnormalized[8], normalized[8];
                INT W = 0;

                ret_code = test_scatter_matrix(D,q,r,h,kappa,1,&lambda,
                        unnormalized,NULL,schemes[method],degree,1);
                CHECK_RETCODE(ret_code, leave_fun);
                ret_code = test_scatter_matrix(D,q,r,h,kappa,1,&lambda,
                        normalized,&W,schemes[method],degree,1);
                CHECK_RETCODE(ret_code, leave_fun);
                if (W == 0) {
                    ret_code = E_TEST_FAILED;
                    goto leave_fun;
                }
                for (UINT j=0; j<8; j++) {
                    const COMPLEX reconstructed = normalized[j]*POW(2,W);
                    const REAL error = CABS(unnormalized[j]-reconstructed);
                    const REAL tolerance = 2000*EPSILON
                            *(1+CABS(unnormalized[j]));
                    if (!isfinite(CREAL(unnormalized[j]))
                            || !isfinite(CIMAG(unnormalized[j]))
                            || !isfinite(CREAL(normalized[j]))
                            || !isfinite(CIMAG(normalized[j]))
                            || !isfinite(CREAL(reconstructed))
                            || !isfinite(CIMAG(reconstructed))
                            || !isfinite(error) || !isfinite(tolerance)
                            || !(error <= tolerance)) {
                        ret_code = E_TEST_FAILED;
                        goto leave_fun;
                    }
                }
            }
        }
    }

leave_fun:
    return ret_code;
}

static INT test_slow_ES_nonfinite_normalization(void)
{
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6,
        nse_discretization_ES8
    };
    const COMPLEX lambda = 0.23;
    COMPLEX q[7] = {NAN}, r[7] = {0};
    INT ret_code = SUCCESS;

    for (UINT method=0; method<3; method++) {
        const UINT D = 2*method+3;
        akns_discretization_t akns_discretization;

        ret_code = nse_discretization_to_akns_discretization(
                schemes[method],&akns_discretization);
        CHECK_RETCODE(ret_code, leave_fun);

        for (UINT degree=0; degree<=7; degree++) {
            COMPLEX unnormalized[4], normalized[4];
            COMPLEX H11, H21;
            UINT nonfinite_count = 0;
            INT W = 0, W_first_column = 0;

            ret_code = test_scatter_matrix(D,q,r,0.05,+1,1,&lambda,
                    unnormalized,NULL,schemes[method],degree,0);
            CHECK_RETCODE(ret_code, leave_fun);
            ret_code = test_scatter_matrix(D,q,r,0.05,+1,1,&lambda,
                    normalized,&W,schemes[method],degree,0);
            CHECK_RETCODE(ret_code, leave_fun);
            ret_code = akns_scatter_matrix_first_column(D,q,r,0.05,1,
                    &lambda,&H11,&H21,&W_first_column,
                    akns_discretization,degree);
            CHECK_RETCODE(ret_code, leave_fun);
            for (UINT j=0; j<4; j++) {
                const int unnormalized_finite =
                        isfinite(CREAL(unnormalized[j]))
                        && isfinite(CIMAG(unnormalized[j]));
                const int normalized_finite = isfinite(CREAL(normalized[j]))
                        && isfinite(CIMAG(normalized[j]));

                if (unnormalized_finite != normalized_finite) {
                    ret_code = E_TEST_FAILED;
                    goto leave_fun;
                }
                if (!normalized_finite)
                    nonfinite_count++;
            }
            if ((isfinite(CREAL(H11)) && isfinite(CIMAG(H11)))
                        != (isfinite(CREAL(normalized[0]))
                            && isfinite(CIMAG(normalized[0])))
                    || (isfinite(CREAL(H21)) && isfinite(CIMAG(H21)))
                        != (isfinite(CREAL(normalized[2]))
                            && isfinite(CIMAG(normalized[2])))
                    || nonfinite_count == 0 || W != 0
                    || W_first_column != W) {
                ret_code = E_TEST_FAILED;
                goto leave_fun;
            }
        }
    }

leave_fun:
    return ret_code;
}

static INT test_slow_ES_first_column_scaling(void)
{
    const nse_discretization_t schemes[3] = {
        nse_discretization_ES4, nse_discretization_ES6,
        nse_discretization_ES8
    };
    enum { nodes = 32 };
    const COMPLEX lambda = 0.0;
    COMPLEX q[7*nodes], r[7*nodes];
    INT ret_code = SUCCESS;

    for (UINT method=0; method<3; method++) {
        const UINT stride = 2*method+3;
        const UINT D = nodes*stride;
        akns_discretization_t akns_discretization;

        ret_code = nse_discretization_to_akns_discretization(
                schemes[method],&akns_discretization);
        CHECK_RETCODE(ret_code, leave_fun);
        for (INT kappa=-1; kappa<=1; kappa+=2) {
            memset(q,0,sizeof(q));
            memset(r,0,sizeof(r));
            for (UINT node=0; node<nodes; node++) {
                q[node*stride] = 0.4;
                r[node*stride] = -0.4*kappa;
            }
            for (UINT degree=0; degree<=7; degree++) {
                COMPLEX full[4], H11, H21;
                INT Wfull = 0, Wcolumn = 0;

                ret_code = test_scatter_matrix(D,q,r,0.05,kappa,1,&lambda,
                        full,&Wfull,schemes[method],degree,0);
                CHECK_RETCODE(ret_code, leave_fun);
                ret_code = akns_scatter_matrix_first_column(D,q,r,0.05,1,
                        &lambda,&H11,&H21,&Wcolumn,akns_discretization,
                        degree);
                CHECK_RETCODE(ret_code, leave_fun);
                if (Wfull != Wcolumn
                        || memcmp(&H11,&full[0],sizeof(COMPLEX)) != 0
                        || memcmp(&H21,&full[2],sizeof(COMPLEX)) != 0
                        || (kappa == -1 && Wcolumn == 0)) {
                    ret_code = E_TEST_FAILED;
                    goto leave_fun;
                }
            }
        }
    }

leave_fun:
    return ret_code;
}

static INT test_constant_and_zero(const INT kappa)
{
    const REAL h = 0.09;
    const COMPLEX lambda = 0.41, value = 0.32 - 0.09 * I;
    COMPLEX samples[7], rsamples[7], q[7], r[7], es8[4], bo[4];
    INT ret_code;
    for (UINT i = 0; i < 7; i++) {
        samples[i] = value;
        rsamples[i] = -kappa * CONJ(value);
    }
    es8_pack(samples, h, q);
    es8_pack(rsamples, h, r);
    ret_code =
        nse_scatter_matrix(7, q, r, h, kappa, 1, &lambda, es8, NULL, nse_discretization_ES8, 0);
    CHECK_RETCODE(ret_code, leave_fun);
    ret_code = nse_scatter_matrix(1, samples, rsamples, h, kappa, 1, &lambda, bo, NULL,
                                  nse_discretization_BO, 0);
    CHECK_RETCODE(ret_code, leave_fun);
    if (misc_rel_err(4, es8, bo) > 100 * EPSILON)
        return E_TEST_FAILED;
    memset(q, 0, sizeof(q));
    memset(r, 0, sizeof(r));
    ret_code =
        nse_scatter_matrix(7, q, r, h, kappa, 1, &lambda, es8, NULL, nse_discretization_ES8, 0);
    CHECK_RETCODE(ret_code, leave_fun);
    bo[0] = CEXP(-I * lambda * h);
    bo[1] = bo[2] = 0.0;
    bo[3] = CEXP(I * lambda * h);
    if (misc_rel_err(4, es8, bo) > 100 * EPSILON)
        return E_TEST_FAILED;
leave_fun:
    return ret_code;
}

/* Compare complete blocks and partial last blocks with a product of
 * independently evaluated single-node transitions, including U'. */
static INT test_slow_ES_block_composition(void)
{
    const UINT sizes[] = {2,31,32,33,63,64,65};
    const nse_discretization_t schemes[] = {
        nse_discretization_ES4,nse_discretization_ES6,nse_discretization_ES8
    };
    const COMPLEX lambda[] = {-0.4,0.6+0.13*(COMPLEX)I};
    const REAL h = 0.02;
    COMPLEX samples[65], *q = NULL, *r = NULL;
    INT ret_code = SUCCESS;

    for (UINT size=0; size<sizeof(sizes)/sizeof(sizes[0]); size++) {
        const UINT N = sizes[size];
        for (UINT n=0; n<N; n++) {
            const REAL t = n*h;
            samples[n] = 0.3+0.12*SIN(3*t)+0.2*(COMPLEX)I*COS(t);
        }
        for (UINT method=0; method<3; method++) {
            const UINT stride = 2*method+3;
            for (INT kappa=-1; kappa<=1; kappa+=2) {
                UINT Dsub = N, first_last[2];
                ret_code = nse_discretization_preprocess_signal(N,samples,h,
                        kappa,&Dsub,&q,&r,first_last,schemes[method]);
                CHECK_RETCODE(ret_code,leave_fun);
                for (UINT degree=0; degree<=7; degree++) {
                    for (UINT point=0; point<2; point++) {
                        COMPLEX reference[8] = {1,0,0,1,0,0,0,0};
                        for (UINT n=0; n<N; n++) {
                            COMPLEX U[8], next[8] = {0};
                            ret_code = test_scatter_matrix(stride,q+stride*n,
                                    r+stride*n,h,kappa,1,&lambda[point],U,
                                    NULL,schemes[method],degree,1);
                            CHECK_RETCODE(ret_code,leave_fun);
                            for (UINT row=0; row<2; row++) {
                                for (UINT col=0; col<2; col++) {
                                    for (UINT k=0; k<2; k++) {
                                        next[2*row+col] += U[2*row+k]
                                                *reference[2*k+col];
                                        next[4+2*row+col] += U[4+2*row+k]
                                                *reference[2*k+col]
                                                +U[2*row+k]*reference[4+2*k+col];
                                    }
                                }
                            }
                            memcpy(reference,next,sizeof(reference));
                        }
                        for (UINT derivative=0; derivative<=1; derivative++) {
                            for (UINT normalize=0; normalize<=1; normalize++) {
                                COMPLEX actual[8];
                                INT W = 0;
                                ret_code = test_scatter_matrix(N*stride,q,r,h,
                                        kappa,1,&lambda[point],actual,
                                        normalize ? &W : NULL,schemes[method],
                                        degree,derivative);
                                CHECK_RETCODE(ret_code,leave_fun);
                                for (UINT j=0; j<(derivative ? 8 : 4); j++) {
                                    const COMPLEX value = actual[j]*POW(2,W);
                                    const REAL tolerance = 128*(N+1)*EPSILON
                                            *(1+CABS(reference[j]));
                                    if (!isfinite(CREAL(value))
                                            || !isfinite(CIMAG(value))
                                            || !(CABS(value-reference[j]) <= tolerance)) {
                                        ret_code = E_TEST_FAILED;
                                        goto leave_fun;
                                    }
                                }
                            }
                        }
                    }
                }
                free(q);
                free(r);
                q = NULL;
                r = NULL;
            }
        }
    }
leave_fun:
    free(q);
    free(r);
    return ret_code;
}

