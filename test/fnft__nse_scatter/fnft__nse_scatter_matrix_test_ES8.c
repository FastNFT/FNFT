static INT test_es_family_traceless_coefficients(void)
{
    const COMPLEX q[7] = {
        0.13+0.02*(COMPLEX)I, -0.07+0.03*(COMPLEX)I,
        0.011-0.04*(COMPLEX)I, 0.021+0.013*(COMPLEX)I,
        -0.008+0.006*(COMPLEX)I, 0.003-0.002*(COMPLEX)I,
        -0.001+0.0004*(COMPLEX)I
    };
    const COMPLEX r[7] = {
        -0.09+0.04*(COMPLEX)I, 0.05+0.01*(COMPLEX)I,
        -0.014-0.009*(COMPLEX)I, 0.006-0.003*(COMPLEX)I,
        0.002+0.004*(COMPLEX)I, -0.001-0.0007*(COMPLEX)I,
        0.0003+0.0002*(COMPLEX)I
    };
    const COMPLEX z_values[4] = {
        0.0, 1e-100*(1.0+(COMPLEX)I), 0.27+0.31*(COMPLEX)I,
        1e4-2e4*(COMPLEX)I
    };
    const UINT orders[3] = {4,6,8};

    for (UINT method=0; method<3; method++) {
        const UINT degree = orders[method]-3;
        COMPLEX coeff[24] = {0};

        fnft__akns_es_z_coefficients(orders[method],q,r,coeff);
        for (UINT k=0; k<=degree; k++) {
            if (!isfinite(CREAL(coeff[4*k]))
                    || !isfinite(CIMAG(coeff[4*k]))
                    || coeff[4*k+3] != -coeff[4*k])
                return E_TEST_FAILED;
        }
        for (UINT point=0; point<4; point++) {
            COMPLEX Z0 = coeff[4*degree], Z3 = coeff[4*degree+3];
            COMPLEX Zd0 = degree*coeff[4*degree];
            COMPLEX Zd3 = degree*coeff[4*degree+3];

            for (UINT k=degree; k-->0; ) {
                Z0 = Z0*z_values[point]+coeff[4*k];
                Z3 = Z3*z_values[point]+coeff[4*k+3];
            }
            for (UINT k=degree; k-->1; ) {
                Zd0 = Zd0*z_values[point]+k*coeff[4*k];
                Zd3 = Zd3*z_values[point]+k*coeff[4*k+3];
            }
            {
                const REAL value_error = CABS(Z3+Z0);
                const REAL derivative_error = CABS(Zd3+Zd0);
                const REAL value_tolerance = 50*EPSILON
                        *(1+CABS(Z0)+CABS(Z3));
                const REAL derivative_tolerance = 50*EPSILON
                        *(1+CABS(Zd0)+CABS(Zd3));

                if (!isfinite(CREAL(Z0)) || !isfinite(CIMAG(Z0))
                        || !isfinite(CREAL(Z3)) || !isfinite(CIMAG(Z3))
                        || !isfinite(CREAL(Zd0)) || !isfinite(CIMAG(Zd0))
                        || !isfinite(CREAL(Zd3)) || !isfinite(CIMAG(Zd3))
                        || !isfinite(value_error)
                        || !isfinite(derivative_error)
                        || !isfinite(value_tolerance)
                        || !isfinite(derivative_tolerance)
                        || !(value_error <= value_tolerance)
                        || !(derivative_error <= derivative_tolerance))
                    return E_TEST_FAILED;
            }
        }
    }
    return SUCCESS;
}

static void reference_exact_scalar_pair(COMPLEX const delta,
        COMPLEX * const f, COMPLEX * const g,
        COMPLEX * const f_delta)
{
    if (CABS(delta) < 1e-8) {
        const COMPLEX delta2 = delta*delta;
        const COMPLEX delta3 = delta2*delta;
        const COMPLEX delta4 = delta3*delta;

        *f = 1.0+delta/2.0+delta2/24.0+delta3/720.0
                +delta4/40320.0;
        *g = 1.0+delta/6.0+delta2/120.0+delta3/5040.0
                +delta4/362880.0;
        *f_delta = 1.0/6.0+delta/60.0+delta2/1680.0
                +delta3/90720.0;
    } else {
        const COMPLEX root = CSQRT(delta);

        *f = CCOSH(root);
        *g = misc_CSINC((COMPLEX)I*root);
        *f_delta = (*f-*g)/(2.0*delta);
    }
}

static INT check_exact_scalar_value(COMPLEX const actual,
                                    COMPLEX const expected,
                                    UINT const signed_zero_flag)
{
    const REAL actual_parts[2] = {CREAL(actual),CIMAG(actual)};
    const REAL expected_parts[2] = {CREAL(expected),CIMAG(expected)};

    for (UINT part=0; part<2; part++) {
        if (isnan(expected_parts[part])) {
            if (!isnan(actual_parts[part]))
                return E_TEST_FAILED;
        } else if (isinf(expected_parts[part])) {
            if (!isinf(actual_parts[part])
                    || signbit(actual_parts[part])
                        != signbit(expected_parts[part]))
                return E_TEST_FAILED;
        } else {
            if (!isfinite(actual_parts[part]))
                return E_TEST_FAILED;
            if (signed_zero_flag && expected_parts[part] == 0.0
                    && actual_parts[part] == 0.0
                    && signbit(actual_parts[part])
                        != signbit(expected_parts[part]))
                return E_TEST_FAILED;
        }
    }
    if (isfinite(expected_parts[0]) && isfinite(expected_parts[1])) {
        const REAL error = CABS(actual-expected);
        const REAL scale = fmax(1.0,fmax(FABS(expected_parts[0]),
                FABS(expected_parts[1])));
        const REAL tolerance = 256*EPSILON*scale;

        if (!isfinite(error) || !isfinite(tolerance)
                || !(error <= tolerance))
            return E_TEST_FAILED;
    }
    return SUCCESS;
}

static COMPLEX reference_complex_multiply(COMPLEX const a,
                                          COMPLEX const b)
{
    return a*b;
}

static COMPLEX reference_complex_multiply_add(COMPLEX const a,
        COMPLEX const b, COMPLEX const c)
{
    return a+b*c;
}

static COMPLEX complex_from_parts(REAL const real, REAL const imag)
{
    const REAL parts[2] = {real,imag};
    COMPLEX value;

    memcpy(&value,parts,sizeof(value));
    return value;
}

static INT test_exact_scalar_pair_shared_hyperbolics(void)
{
    const REAL re[] = {-700.0,-100.0,-20.0,-1.0,-0.1,-1e-12,-1e-300,
            -0.0,0.0,1e-300,1e-12,0.1,1.0,20.0,100.0,700.0};
    const REAL im[] = {-1e6,-3.0,-0.1,-1e-12,-0.0,0.0,1e-12,0.1,3.0,1e6};

    for (UINT i=0; i<sizeof(re)/sizeof(re[0]); i++) {
        for (UINT j=0; j<sizeof(im)/sizeof(im[0]); j++) {
            const COMPLEX root = complex_from_parts(re[i],im[j]);
            const COMPLEX reference[2] = {CCOSH(root),misc_CSINC((COMPLEX)I*root)};
            COMPLEX actual[2];

            fnft__akns_scatter_exact_scalar_pair(root,&actual[0],&actual[1]);
            for (UINT k=0; k<2; k++) {
                const REAL scale = fmax(1.0,fmax(FABS(CREAL(reference[k])),
                        FABS(CIMAG(reference[k]))));
                if (!isfinite(CREAL(actual[k])) || !isfinite(CIMAG(actual[k]))
                        || !(CABS(actual[k]-reference[k]) <= 16*EPSILON*scale))
                    return E_TEST_FAILED;
            }
        }
    }
    return SUCCESS;
}

static INT test_exact_scalar_pair_signed_zeros(void)
{
    const COMPLEX roots[] = {
        complex_from_parts(0.0,0.0),
        complex_from_parts(-0.0,0.0),
        complex_from_parts(0.0,-0.0),
        complex_from_parts(-0.0,-0.0),
        complex_from_parts(1.0,0.0),
        complex_from_parts(1.0,-0.0),
        complex_from_parts(0.0,1.0),
        complex_from_parts(-0.0,1.0),
        complex_from_parts(0.0,-1.0),
        complex_from_parts(-0.0,-1.0),
        complex_from_parts(1.0,1.0),
        complex_from_parts(1.0,-1.0),
        CSQRT(1e300), CSQRT(-1e300),
        complex_from_parts(-0.0,1e150),
        complex_from_parts(0.0,-1e150),
        complex_from_parts(-0.0,-1e150),
        CSQRT(1e300+(COMPLEX)I*1e300),
        complex_from_parts(INFINITY,0.0),
        complex_from_parts(NAN,1.0)
    };
    UINT signbit_checks = 0;

    for (UINT point=0; point<sizeof(roots)/sizeof(roots[0]); point++) {
        COMPLEX actual_f, actual_g;
        const COMPLEX expected_f = CCOSH(roots[point]);
        const COMPLEX expected_g = misc_CSINC((COMPLEX)I*roots[point]);
        const REAL expected_parts[4] = {
            CREAL(expected_f),CIMAG(expected_f),
            CREAL(expected_g),CIMAG(expected_g)
        };
        REAL actual_parts[4];
        INT ret_code;

        fnft__akns_scatter_exact_scalar_pair(roots[point],
                &actual_f,&actual_g);
        actual_parts[0] = CREAL(actual_f);
        actual_parts[1] = CIMAG(actual_f);
        actual_parts[2] = CREAL(actual_g);
        actual_parts[3] = CIMAG(actual_g);
        ret_code = check_exact_scalar_value(actual_f,expected_f,1);
        if (ret_code == SUCCESS)
            ret_code = check_exact_scalar_value(actual_g,expected_g,1);
        if (ret_code != SUCCESS)
            return ret_code;
        for (UINT part=0; part<4; part++) {
            if (expected_parts[part] == 0.0) {
                signbit_checks++;
                if (actual_parts[part] != 0.0
                        || signbit(actual_parts[part])
                            != signbit(expected_parts[part]))
                    return E_TEST_FAILED;
            }
        }
    }
    return signbit_checks >= 20 ? SUCCESS : E_TEST_FAILED;
}

static INT test_exact_scalar_pair_derivative_grid(void)
{
    const COMPLEX targets[] = {
        0.5e-8, 2.0e-8, 1.0+0.3*(COMPLEX)I,
        490000.0+1e-6*(COMPLEX)I,
        500000.0+1e-6*(COMPLEX)I
    };
    const COMPLEX lambda = 1.0/1024.0;

    for (UINT point=0; point<sizeof(targets)/sizeof(targets[0]); point++) {
        const COMPLEX potential = CSQRT(targets[point]+lambda*lambda);
        COMPLEX q[3] = {potential,0.0,0.0};
        COMPLEX r[3] = {potential,0.0,0.0};
        COMPLEX coeff[8], Z[4], Zd[4], actual[8], expected[8];
        COMPLEX f, g, signed_g, f_delta, f_d, g_d, delta, delta_d;
        COMPLEX (* volatile multiply)(COMPLEX,COMPLEX) =
                reference_complex_multiply;
        COMPLEX (* volatile multiply_add)(COMPLEX,COMPLEX,COMPLEX) =
                reference_complex_multiply_add;
        INT ret_code;

        fnft__akns_es_z_coefficients(4,q,r,coeff);
        for (UINT j=0; j<4; j++) {
            Z[j] = multiply_add(coeff[j],coeff[4+j],lambda);
            Zd[j] = coeff[4+j];
        }
        delta = multiply(Z[0],Z[0])+multiply(Z[1],Z[2]);
        delta_d = multiply(2.0*multiply(Z[0],Zd[0]),1.0)
                +multiply(Zd[1],Z[2])+multiply(Z[1],Zd[2]);
        if (!isfinite(CREAL(delta_d)) || !isfinite(CIMAG(delta_d))
                || CABS(delta_d) == 0.0)
            return E_TEST_FAILED;
        reference_exact_scalar_pair(delta,&f,&g,&f_delta);
        signed_g = multiply((COMPLEX)1.0,g);
        f_d = multiply(0.5*g,delta_d);
        g_d = multiply(f_delta,delta_d);
        expected[0] = multiply_add(f,signed_g,Z[0]);
        expected[1] = multiply(signed_g,Z[1]);
        expected[2] = multiply(signed_g,Z[2]);
        expected[3] = multiply_add(f,signed_g,Z[3]);
        expected[4] = multiply_add(f_d,(COMPLEX)1.0,
                multiply(g_d,Z[0])+multiply(g,Zd[0]));
        expected[5] = multiply((COMPLEX)1.0,
                multiply(g_d,Z[1])+multiply(g,Zd[1]));
        expected[6] = multiply((COMPLEX)1.0,
                multiply(g_d,Z[2])+multiply(g,Zd[2]));
        expected[7] = multiply_add(f_d,(COMPLEX)1.0,
                multiply(g_d,Z[3])+multiply(g,Zd[3]));
        ret_code = nse_scatter_matrix(3,q,r,1.0,+1,1,&lambda,actual,NULL,
                nse_discretization_ES4,1);
        CHECK_RETCODE(ret_code, leave_fun);
        for (UINT j=0; j<8; j++) {
            ret_code = check_exact_scalar_value(actual[j],expected[j],0);
            if (ret_code != SUCCESS) {
                fprintf(stderr,"scalar derivative grid point=%lu "
                        "component=%lu delta=(%.17g,%.17g) "
                        "delta_d=(%.17g,%.17g) actual=(%.17g,%.17g) "
                        "expected=(%.17g,%.17g)\n",
                        (unsigned long)point,(unsigned long)j,
                        CREAL(delta),CIMAG(delta),CREAL(delta_d),
                        CIMAG(delta_d),CREAL(actual[j]),CIMAG(actual[j]),
                        CREAL(expected[j]),CIMAG(expected[j]));
                goto leave_fun;
            }
        }
    }
    return SUCCESS;

leave_fun:
    return E_TEST_FAILED;
}

/* A one-node ES4 step with lambda=0 and Z=[0,1;delta,0] exposes the
 * scalar pair through U00=f and U01=g. This retains the previous complex
 * library calls as an independent reference and also checks propagated U'. */
static INT test_exact_scalar_pair_grid(void)
{
    const REAL pi = acos(-1.0);
    const COMPLEX deltas[] = {
        0.0, -0.0, 0.0-(COMPLEX)I*0.0, -0.0-(COMPLEX)I*0.0,
        DBL_MIN/2.0, 0.5e-8, nextafter(1e-8,0.0), 1e-8,
        nextafter(1e-8,INFINITY), 1.0, -1.0,
        (COMPLEX)I, -(COMPLEX)I, 1.0+(COMPLEX)I,
        1.0-(COMPLEX)I, -1.0+(COMPLEX)I, -1.0-(COMPLEX)I,
        -pi*pi, -(pi-1e-8)*(pi-1e-8),
        -(pi+1e-8)*(pi+1e-8), 1e4, -1e4,
        1e4+1e4*(COMPLEX)I,
        NAN, INFINITY, -INFINITY, NAN+(COMPLEX)I,
        1.0+(COMPLEX)I*INFINITY
    };
    const COMPLEX lambda = 0.0;

    for (UINT point=0; point<sizeof(deltas)/sizeof(deltas[0]); point++) {
        COMPLEX q[3] = {1.0,0.0,0.0};
        COMPLEX r[3] = {deltas[point],0.0,0.0};
        COMPLEX actual[8], f, g, f_delta, expected[8];
        volatile COMPLEX Z_reference[4] = {
            0.0,1.0,deltas[point],-0.0
        };
        volatile COMPLEX Zd_reference[4] = {
            -(COMPLEX)I,0.0,0.0,(COMPLEX)I
        };
        const COMPLEX z0 = Z_reference[0], z1 = Z_reference[1];
        const COMPLEX z2 = Z_reference[2], z3 = Z_reference[3];
        const COMPLEX zd0 = Zd_reference[0], zd1 = Zd_reference[1];
        const COMPLEX zd2 = Zd_reference[2], zd3 = Zd_reference[3];
        COMPLEX (* volatile multiply)(COMPLEX,COMPLEX) =
                reference_complex_multiply;
        COMPLEX (* volatile multiply_add)(COMPLEX,COMPLEX,COMPLEX) =
                reference_complex_multiply_add;
        const COMPLEX delta_reference = multiply(z0,z0)+multiply(z1,z2);
        const COMPLEX delta_d = multiply(2.0*multiply(z0,zd0),1.0)
                +multiply(zd1,z2)+multiply(z1,zd2);
        COMPLEX f_d, g_d;
        INT ret_code;

        reference_exact_scalar_pair(delta_reference,&f,&g,&f_delta);
        f_d = multiply(0.5*g,delta_d);
        g_d = multiply(f_delta,delta_d);
        expected[0] = multiply_add(f,g,z0);
        expected[1] = multiply(g,z1);
        expected[2] = multiply(g,z2);
        expected[3] = multiply_add(f,g,z3);
        expected[4] = multiply_add(multiply_add(f_d,g_d,z0),g,zd0);
        expected[5] = multiply(g_d,z1);
        expected[6] = multiply(g_d,z2);
        expected[7] = multiply_add(multiply_add(f_d,g_d,z3),g,zd3);
        ret_code = nse_scatter_matrix(3,q,r,1.0,+1,1,&lambda,actual,NULL,
                nse_discretization_ES4,1);
        CHECK_RETCODE(ret_code, leave_fun);
        for (UINT j=0; j<8; j++) {
            /* Matrix materialization/multiplication may canonicalize signed
             * zeros even when the scalar pair retains them. */
            ret_code = check_exact_scalar_value(actual[j],expected[j],0);
            if (ret_code != SUCCESS) {
                fprintf(stderr,"scalar pair grid point=%lu component=%lu "
                        "delta=(%.17g,%.17g) actual=(%.17g,%.17g) "
                        "expected=(%.17g,%.17g)\n",
                        (unsigned long)point,(unsigned long)j,
                        CREAL(deltas[point]),CIMAG(deltas[point]),
                        CREAL(actual[j]),CIMAG(actual[j]),
                        CREAL(expected[j]),CIMAG(expected[j]));
                goto leave_fun;
            }
        }
    }
    return SUCCESS;

leave_fun:
    return E_TEST_FAILED;
}

/* The full scattering-matrix path applies a change of basis after U. Near
 * overflow that later algebra can introduce Inf-Inf independently of the
 * scalar pair. The ES first-column path has no such change of basis. A
 * balanced Z01=Z10=sqrt(delta) keeps both off-diagonal entries finite up to
 * the fallback boundary. For nonfinite inputs, form the reference with the
 * same matrix-vector algebra and compare its classification fail-closed. */
static INT test_exact_scalar_pair_extremes(void)
{
    const REAL safe_root = log(DBL_MAX)-8.0;
    const COMPLEX deltas[] = {
        safe_root*safe_root,
        (safe_root+1.0)*(safe_root+1.0),
        490000.0+(COMPLEX)I*1e-6,
        500000.0+(COMPLEX)I*1e-6,
        1e300, -1e300, 1e300+(COMPLEX)I*1e300,
        INFINITY, NAN+(COMPLEX)I
    };
    const COMPLEX lambda = 0.0;

    for (UINT point=0; point<sizeof(deltas)/sizeof(deltas[0]); point++) {
        const COMPLEX root = CSQRT(deltas[point]);
        COMPLEX q[3] = {root,0.0,0.0};
        COMPLEX r[3] = {root,0.0,0.0};
        COMPLEX coeff[8], actual_f, actual_g, expected_f, expected_g;
        COMPLEX f, g, f_delta, expected_materialized_f;
        COMPLEX expected_materialized_g, recovered_g;
        COMPLEX (* volatile multiply)(COMPLEX,COMPLEX) =
                reference_complex_multiply;
        COMPLEX (* volatile multiply_add)(COMPLEX,COMPLEX,COMPLEX) =
                reference_complex_multiply_add;
        COMPLEX delta_reference;
        INT ret_code;

        fnft__akns_es_z_coefficients(4,q,r,coeff);
        delta_reference = multiply(coeff[0],coeff[0])
                +multiply(coeff[1],coeff[2]);
        reference_exact_scalar_pair(delta_reference,&f,&g,&f_delta);
        expected_f = multiply_add(f,g,coeff[0]);
        expected_g = multiply(g,coeff[2]);
        expected_materialized_f = multiply_add(expected_f,
                multiply(g,coeff[1]),0.0);
        expected_materialized_g = multiply_add(expected_g,
                multiply_add(f,g,coeff[3]),0.0);
        ret_code = akns_scatter_matrix_first_column(3,q,r,1.0,1,&lambda,
                &actual_f,&actual_g,NULL,akns_discretization_ES4,0);
        CHECK_RETCODE(ret_code, leave_fun);
        ret_code = check_exact_scalar_value(actual_f,
                expected_materialized_f,0);
        if (ret_code == SUCCESS)
            ret_code = check_exact_scalar_value(actual_g,
                    expected_materialized_g,0);
        if (ret_code == SUCCESS && isfinite(CREAL(root))
                && isfinite(CIMAG(root)) && CABS(root) != 0.0
                && isfinite(CREAL(actual_g))
                && isfinite(CIMAG(actual_g))) {
            recovered_g = actual_g/root;
            ret_code = check_exact_scalar_value(recovered_g,g,0);
        }
        if (ret_code != SUCCESS) {
            fprintf(stderr,"scalar pair extreme point=%lu "
                    "delta=(%.17g,%.17g) f=(%.17g,%.17g) "
                    "f_ref=(%.17g,%.17g) g=(%.17g,%.17g) "
                    "g_ref=(%.17g,%.17g)\n",
                    (unsigned long)point,CREAL(deltas[point]),
                    CIMAG(deltas[point]),CREAL(actual_f),CIMAG(actual_f),
                    CREAL(expected_materialized_f),
                    CIMAG(expected_materialized_f),CREAL(actual_g),
                    CIMAG(actual_g),CREAL(expected_materialized_g),
                    CIMAG(expected_materialized_g));
            goto leave_fun;
        }
    }
    return SUCCESS;

leave_fun:
    return E_TEST_FAILED;
}

static void es8_pack(COMPLEX const f[7], REAL const h, COMPLEX out[7])
{
    out[0] = h * f[3];
    out[1] = h * (-f[0] / 60.0 + 3.0 * f[1] / 20.0 - 3.0 * f[2] / 4.0 + 3.0 * f[4] / 4.0 -
                  3.0 * f[5] / 20.0 + f[6] / 60.0);
    out[2] = h * (f[0] / 90.0 - 3.0 * f[1] / 20.0 + 3.0 * f[2] / 2.0 - 49.0 * f[3] / 18.0 +
                  3.0 * f[4] / 2.0 - 3.0 * f[5] / 20.0 + f[6] / 90.0);
    out[3] = h * (f[0] / 8.0 - f[1] + 13.0 * f[2] / 8.0 - 13.0 * f[4] / 8.0 + f[5] - f[6] / 8.0);
    out[4] = h * (-f[0] / 6.0 + 2.0 * f[1] - 13.0 * f[2] / 2.0 + 28.0 * f[3] / 3.0 -
                  13.0 * f[4] / 2.0 + 2.0 * f[5] - f[6] / 6.0);
    out[5] = h * (-f[0] / 2.0 + 2.0 * f[1] - 5.0 * f[2] / 2.0 + 5.0 * f[4] / 2.0 - 2.0 * f[5] +
                  f[6] / 2.0);
    out[6] = h * (f[0] - 6.0 * f[1] + 15.0 * f[2] - 20.0 * f[3] + 15.0 * f[4] - 6.0 * f[5] + f[6]);
}

